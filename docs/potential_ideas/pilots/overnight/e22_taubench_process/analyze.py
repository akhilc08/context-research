"""Regenerate every E22 table from the raw result files (standard library plus detectors.py).

Usage: python3 analyze.py results/retail.jsonl results/airline.jsonl > results/tables.md
"""
import collections, json, math, random, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import detectors as D  # noqa: E402

ORDER = ["nopolicy", "hist", "compact", "pin", "pinrules", "watch"]
PLANNED = [("compact", "hist"), ("pin", "compact"), ("pinrules", "compact"), ("watch", "compact"),
           ("watch", "pinrules"), ("nopolicy", "hist")]


def load(p):
    return [json.loads(l) for l in Path(p).read_text().splitlines() if l.strip()]


def wilson(k, n, z=1.96):
    if n == 0:
        return float("nan"), float("nan")
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return c - h, c + h


def sign_p(k, n):
    if n == 0:
        return 1.0
    pk = [math.comb(n, i) / 2 ** n for i in range(n + 1)]
    return min(1.0, sum(p for p in pk if p <= pk[k] + 1e-12))


def boot(diffs, reps=2000, seed=0):
    rng = random.Random(seed)
    n = len(diffs)
    if not n:
        return float("nan"), float("nan")
    ms = sorted(sum(diffs[rng.randrange(n)] for _ in range(n)) / n for _ in range(reps))
    return ms[int(0.025 * reps)], ms[int(0.975 * reps) - 1]


def holm(ps):
    idx = sorted(range(len(ps)), key=lambda i: ps[i])
    adj, run = [0.0] * len(ps), 0.0
    for r, i in enumerate(idx):
        run = max(run, min(1.0, (len(ps) - r) * ps[i]))
        adj[i] = run
    return adj


def f3(x):
    return f"{x:.3f}"


def paired(by_arm, a, b, val, exclude=()):
    va = {(r["task"], r["trial"]): val(r) for r in by_arm.get(a, []) if r["task"] not in exclude}
    vb = {(r["task"], r["trial"]): val(r) for r in by_arm.get(b, []) if r["task"] not in exclude}
    shared = sorted(set(va) & set(vb))
    tasks = sorted({t for t, _ in shared})
    ma, mb = {}, {}
    for t in tasks:
        ks = [k for k in shared if k[0] == t]
        ma[t] = sum(va[k] for k in ks) / len(ks)
        mb[t] = sum(vb[k] for k in ks) / len(ks)
    w = sum(ma[t] > mb[t] for t in tasks)
    l = sum(ma[t] < mb[t] for t in tasks)
    n = max(1, len(tasks))
    # run-level discordant pairs (McNemar counts) for reference
    b10 = sum(1 for k in shared if va[k] and not vb[k])
    b01 = sum(1 for k in shared if vb[k] and not va[k])
    return {"a": a, "b": b, "tasks": len(tasks), "runs": len(shared), "w": w, "l": l,
            "ra": sum(ma.values()) / n, "rb": sum(mb.values()) / n,
            "ci": boot([ma[t] - mb[t] for t in tasks]), "p": sign_p(w, w + l), "b10": b10, "b01": b01}


def comparisons_table(fams, title, what):
    print(f"\n## {title}\n")
    print(f"Exact two-sided sign test over tasks on each task's mean {what} across shared trials; "
          "difference with paired bootstrap 95% CI over tasks; Holm across all rows of this table. "
          "'runs a only / b only' are run-level discordant pairs (McNemar counts).\n")
    print("| domain | comparison | tasks | a higher / b higher (tasks) | runs a only / b only | rate a | rate b | "
          "difference (95% CI) | p | Holm p |")
    print("|---|---|---|---|---|---|---|---|---|---|")
    allres = [(d, x) for d, xs in fams for x in xs]
    adj = holm([x["p"] for _, x in allres])
    for (d, x), pa in zip(allres, adj):
        print(f"| {d} | {x['a']} vs {x['b']} | {x['tasks']} | {x['w']} / {x['l']} | {x['b10']} / {x['b01']} | "
              f"{f3(x['ra'])} | {f3(x['rb'])} | {x['ra']-x['rb']:+.3f} ({x['ci'][0]:+.3f} to {x['ci'][1]:+.3f}) | "
              f"{x['p']:.3g} | {pa:.3g} |")


def pass_k(rs, k):
    per = collections.defaultdict(list)
    for r in rs:
        per[r["task"]].append(r["reward"])
    vals = [math.comb(sum(x >= 1 for x in v), k) / math.comb(len(v), k) for v in per.values() if len(v) >= k]
    return sum(vals) / len(vals) if vals else float("nan")


def first_write_exposed(r):
    comp_steps = [c["agent_step"] for c in r["compactions"]]
    for e in r["events"]:
        if e[0] == "tool" and e[1] in D.WRITES[r["domain"]]:
            return bool(comp_steps) and min(comp_steps) < e[4]
    return None


def main(paths):
    data = {}
    for p in paths:
        rows = load(p)
        if rows:
            data[rows[0]["domain"]] = rows
    print(f"# E22 tables (generated by analyze.py from {', '.join(paths)})")
    viol_fams, rew_fams, sens_fams, conf_fams, fix_fams = [], [], [], [], []
    for dom, rows in data.items():
        for r in rows:
            r["_d"] = D.analyze(r)
            r["_v"] = int(D.primary_violation(r, r["_d"]))
            r["_vf"] = int(D.primary_violation(r, fixed=True))
        by_arm = collections.defaultdict(list)
        for r in rows:
            by_arm[r["arm"]].append(r)
        arms = [a for a in ORDER if a in by_arm]
        print(f"\n# {dom}\n")
        print("| arm | runs | tasks | violation rate (95% CI) | reward (95% CI) | pass^2 | model calls/run | "
              "agent calls/run | input tok/run | output tok/run | API calls/run (cache misses) | compactions/run |")
        print("|---|---|---|---|---|---|---|---|---|---|---|---|")
        for a in arms:
            rs = by_arm[a]
            n = len(rs)
            kv = sum(r["_v"] for r in rs)
            kr = sum(r["reward"] >= 1 for r in rs)
            lv, hv = wilson(kv, n)
            lr, hr = wilson(kr, n)
            calls = sum(sum(r["calls"].values()) for r in rs) / n
            ag = sum(r["calls"].get("agent", 0) for r in rs) / n
            ti = sum(sum(r["tok_in"].values()) for r in rs) / n
            to = sum(sum(r["tok_out"].values()) for r in rs) / n
            api = sum(r["api_calls"] for r in rs) / n
            nc = sum(r["n_compactions"] for r in rs) / n
            print(f"| {a} | {n} | {len({r['task'] for r in rs})} | {f3(kv/n)} ({lv:.3f} to {hv:.3f}) | "
                  f"{f3(kr/n)} ({lr:.3f} to {hr:.3f}) | {f3(pass_k(rs, 2))} | {calls:.1f} | {ag:.1f} | "
                  f"{ti:,.0f} | {to:,.0f} | {api:.1f} | {nc:.2f} |")
        cats = D.PRIMARY[dom] + D.SECONDARY
        print(f"\n## {dom}: share of runs where each detector fires\n")
        print("| arm | " + " | ".join(cats) + " | runs with a write | writes/run |")
        print("|---|" + "---|" * (len(cats) + 2))
        for a in arms:
            rs = by_arm[a]
            n = len(rs)
            ww = sum(1 for r in rs if r["_d"]["writes"])
            print(f"| {a} | " + " | ".join(f"{sum(c in r['_d']['run'] for r in rs)/n:.3f}" for c in cats) +
                  f" | {ww/n:.3f} | {sum(len(r['_d']['writes']) for r in rs)/n:.2f} |")
        viol_fams.append((dom, [paired(by_arm, a, b, lambda r: r["_v"]) for a, b in PLANNED]))
        rew_fams.append((dom, [paired(by_arm, a, b, lambda r: r["reward"]) for a, b in PLANNED]))
        ex = D.GOLD_CONFLICT.get(dom, set())
        sens_fams.append((dom, [paired(by_arm, a, b, lambda r: r["_v"], ex) for a, b in PLANNED]))
        fix_fams.append((dom, [paired(by_arm, a, b, lambda r: r["_vf"]) for a, b in PLANNED]))
        print(f"\n## {dom}: violation rate with the post-hoc corrected confirmation detector (exploratory)\n")
        print("| arm | violation rate (95% CI) |\n|---|---|")
        for a in arms:
            rs = by_arm[a]
            k = sum(r["_vf"] for r in rs)
            lo, hi = wilson(k, len(rs))
            print(f"| {a} | {k/len(rs):.3f} ({lo:.3f} to {hi:.3f}) |")
        conf_fams.append((dom, [paired(by_arm, a, b, lambda r: int("confirm" in r["_d"]["run"]))
                                for a, b in PLANNED]))
        # exposure
        print(f"\n## {dom}: was the policy compacted away before the first write?\n")
        print("| arm | runs with a write | compaction before first write | violation rate if exposed | if not |")
        print("|---|---|---|---|---|")
        for a in ("compact", "pin", "pinrules", "watch"):
            ex_, nex = [], []
            for r in by_arm.get(a, []):
                e = first_write_exposed(r)
                if e is None:
                    continue
                (ex_ if e else nex).append(r["_v"])
            g = lambda xs: f"{sum(xs)/len(xs):.3f} (n={len(xs)})" if xs else "n/a"
            print(f"| {a} | {len(ex_)+len(nex)} | {len(ex_)} | {g(ex_)} | {g(nex)} |")
        # watchpoint selectivity
        checks = [c for r in by_arm.get("watch", []) for c in r["compactions"]]
        if checks:
            nr = len(json.loads((HERE / f"rules_{dom}.json").read_text()))
            rel = [len(c["relevant"]) for c in checks]
            pat = [len(c["patched"]) for c in checks]
            print(f"\n## {dom}: Watchpoint selectivity\n")
            print(f"- checks: {len(checks)}; judge output parsed: {sum(c['judge_ok'] for c in checks)}")
            print(f"- rules judged relevant per check: mean {sum(rel)/len(rel):.2f} of {nr}")
            print(f"- rules patched per check: mean {sum(pat)/len(pat):.2f} of {nr} "
                  f"(pinrules re-attaches all {nr}); checks that patched nothing: "
                  f"{sum(p == 0 for p in pat)} ({sum(p == 0 for p in pat)/len(pat):.3f})")
            miss = collections.Counter(i for c in checks for i in c["patched"])
            relc = collections.Counter(i for c in checks for i in c["relevant"])
            print("- per rule, share of checks judged relevant / patched: " + ", ".join(
                f"R{i} {relc[i]/len(checks):.2f}/{miss[i]/len(checks):.2f}" for i in range(nr)))
        # failure source
        print(f"\n## {dom}: reward failure source\n")
        print("| arm | failed | wrong DB state | DB right, missing output | max steps |")
        print("|---|---|---|---|---|")
        for a in arms:
            fl = [r for r in by_arm[a] if r["reward"] < 1]
            db = sum(1 for r in fl if r["done"] and "r_actions" in ((r.get("reward_info") or {}).get("info") or {}))
            ms = sum(1 for r in fl if not r["done"])
            print(f"| {a} | {len(fl)} | {db} | {len(fl)-db-ms} | {ms} |")
    comparisons_table(viol_fams, "Primary: planned comparisons on process-violation presence", "violation presence")
    comparisons_table(rew_fams, "Secondary: planned comparisons on τ-bench reward", "reward")
    comparisons_table(sens_fams, "Sensitivity: violation presence without tasks whose gold actions trip a detector",
                      "violation presence")
    comparisons_table(fix_fams, "Exploratory: violation presence with the post-hoc corrected confirmation detector",
                      "violation presence")
    comparisons_table(conf_fams, "Secondary: the confirmation detector alone", "confirm-flag presence")


if __name__ == "__main__":
    main(sys.argv[1:] or ["results/retail.jsonl", "results/airline.jsonl"])
