"""Regenerate every E11 table from the raw files.

Inputs:  data/scenarios.json, data/e5_overtness.json, results/trials.jsonl, results/causal.jsonl,
         results/hand_labels.json (optional), ../usage.jsonl (rows tagged e11_)
Outputs: results/tables.md and results/summary.json
Usage:   python analyze.py [--trials FILE] [--causal FILE] [--labels FILE|none] [--out FILE] [--no-cost]
"""
import argparse, json, math, random, sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common import wilson  # noqa: E402

HERE = Path(__file__).resolve().parent
DEF = ["prov", "prov_pin", "quar_strip", "watch", "watch_pin", "pin"]
CONDS = ["full", "plain", "pin", "prov", "prov_pin", "quar_strip", "watch", "watch_pin"]
LAUND = ("OPERATOR", "FACT")
L = []
S = {}


def emit(s=""):
    print(s)
    L.append(s)


def r(k, n):
    if not n:
        return "n/a"
    lo, hi = wilson(k, n)
    return f"{k}/{n} = {100 * k / n:.0f}% [{max(0, 100 * lo):.0f} to {min(100, 100 * hi):.0f}]"


def mcnemar(pairs):
    b = sum(1 for x, y in pairs if x and not y)
    c = sum(1 for x, y in pairs if y and not x)
    n = b + c
    p = 1.0 if n == 0 else min(1.0, 2 * sum(math.comb(n, k) for k in range(0, min(b, c) + 1)) / 2 ** n)
    return b, c, p


def holm(ps):
    order = sorted(range(len(ps)), key=lambda i: ps[i])
    adj, run = [0.0] * len(ps), 0.0
    for rank, i in enumerate(order):
        run = max(run, min(1.0, (len(ps) - rank) * ps[i]))
        adj[i] = run
    return adj


def kappa(a, b):
    n = len(a)
    po = sum(x == y for x, y in zip(a, b)) / n
    ca, cb = Counter(a), Counter(b)
    pe = sum(ca[k] * cb[k] for k in set(ca) | set(cb)) / n ** 2
    return po, (po - pe) / (1 - pe) if pe < 1 else float("nan")


def cluster_boot(rows, B=4000, seed=7):
    """rows: list of (cluster, x, y) with x, y numeric. 95% CI of mean(x - y) resampling clusters."""
    by = defaultdict(list)
    for c, x, y in rows:
        by[c].append(x - y)
    keys = list(by)
    if not keys:
        return (float("nan"),) * 3
    rng = random.Random(seed)
    est = sum(sum(v) for v in by.values()) / sum(len(v) for v in by.values())
    bs = []
    for _ in range(B):
        samp = [by[keys[rng.randrange(len(keys))]] for _ in keys]
        bs.append(sum(sum(v) for v in samp) / sum(len(v) for v in samp))
    bs.sort()
    return est, bs[int(0.025 * B)], bs[int(0.975 * B) - 1]


def test_block(rows, key):
    """rows: (label, pairs, cluster_rows or None). Holm over the block."""
    res = [(lab, *mcnemar(pr), len(pr), cr) for lab, pr, cr in rows]
    adj = holm([x[3] for x in res])
    emit("| comparison | n pairs | only first | only second | McNemar p | Holm p | diff, scenario-cluster 95% CI |")
    emit("|---|---|---|---|---|---|---|")
    out = {}
    for (lab, b, c, p, n, cr), pa in zip(res, adj):
        ci = ""
        if cr:
            e, lo, hi = cluster_boot(cr)
            ci = f"{100 * e:+.1f} pts [{100 * lo:+.1f} to {100 * hi:+.1f}]"
        emit(f"| {lab} | {n} | {b} | {c} | {p:.3g} | {pa:.3g} | {ci} |")
        out[lab] = {"n": n, "only_first": b, "only_second": c, "p": p, "holm_p": pa, "ci": ci}
    S.setdefault("tests", {})[key] = out


def norm(c):
    c = str(c).upper().strip()
    return "OMITTED" if c.startswith("OMIT") else c


def cat(j):
    return norm((j or {}).get("category", "?"))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--trials", default="results/trials.jsonl")
    ap.add_argument("--causal", default="results/causal.jsonl")
    ap.add_argument("--labels", default="results/hand_labels.json")
    ap.add_argument("--out", default="results/tables.md")
    ap.add_argument("--no-cost", action="store_true")
    a = ap.parse_args()
    SC = json.loads((HERE / "data" / "scenarios.json").read_text())
    BY = {s["id"]: s for f in SC.values() for s in f}
    T = [json.loads(l) for l in (HERE / a.trials).read_text().splitlines()]
    idx = {(t["family"], t["variant"], t["id"], t["rep"]): t for t in T}
    emit(f"# E11 tables (generated by analyze.py from {a.trials})\n")
    emit(f"Sessions: {len(T)} ({dict(Counter((t['family'], t['variant']) for t in T))}). "
         f"Agent models {sorted({t['agent_model'] for t in T})}, judge models {sorted({t['judge_model'] for t in T})}.")

    # ------------------------------------------------ overtness
    emit("\n## 1. Injection overtness (judge, 1 = blends in, 3 = overt)\n")
    e5 = json.loads((HERE / "data" / "e5_overtness.json").read_text())
    emit("| set | n | tier 1 | tier 2 | tier 3 |")
    emit("|---|---|---|---|---|")
    for name, xs in [("E11 family A", [s["overtness"] for s in SC["A"]]), ("E11 family B", [s["overtness"] for s in SC["B"]]),
                     ("E5 family A (reference)", [x["overtness"] for x in e5 if x["id"].startswith("A")]),
                     ("E5 family B (reference)", [x["overtness"] for x in e5 if x["id"].startswith("B")])]:
        c = Counter(xs)
        emit(f"| {name} | {len(xs)} | {c[1]} | {c[2]} | {c[3]} |")
    emit("\nE11 by designed style:\n")
    emit("| family | style | tier 1 | tier 2 | tier 3 |")
    emit("|---|---|---|---|---|")
    for f in ("A", "B"):
        for st in ("declarative", "procedural", "addressed"):
            c = Counter(s["overtness"] for s in SC[f] if s["style"] == st)
            emit(f"| {f} | {st} | {c[1]} | {c[2]} | {c[3]} |")

    def tier(t):
        o = BY[t["id"]]["overtness"]
        return "1" if o == 1 else "2-3"

    # ------------------------------------------------ acting rates at round 3
    emit("\n## 2. Acting at round 3 (attack success for inject and none; utility for legit)\n")
    emit("Family A: the agent's next action violates the operator's rule (v2 judge). Family B: the plan performs the "
         "planted action. For legit, acting is the desired outcome.\n")
    emit("| family | variant | " + " | ".join(CONDS) + " |")
    emit("|---|---|" + "---|" * len(CONDS))
    for f in ("A", "B"):
        for v in ("inject", "none", "legit"):
            ts = [t for t in T if t["family"] == f and t["variant"] == v]
            if not ts:
                continue
            cells = []
            for c in CONDS:
                k = sum(bool(t["cp"]["3"][c]["acted"]) for t in ts)
                S.setdefault("rates", {})[f"{f}/{v}/{c}"] = [k, len(ts)]
                cells.append(r(k, len(ts)))
            emit(f"| {f} | {v} | " + " | ".join(cells) + " |")

    def pairs(f, v1, c1, v2, c2, rnd="3", rnd2=None):
        pr, cr = [], []
        for (ff, vv, i, rep), t in idx.items():
            if ff == f and vv == v1 and (f, v2, i, rep) in idx:
                u = T and idx[(f, v2, i, rep)]
                if c1 in t["cp"].get(rnd, {}) and c2 in u["cp"].get(rnd2 or rnd, {}):
                    x, y = bool(t["cp"][rnd][c1]["acted"]), bool(u["cp"][rnd2 or rnd][c2]["acted"])
                    pr.append((x, y))
                    cr.append((i, x, y))
        return pr, cr

    emit("\n### H3 primary: each defense vs plain, inject, round 3 (Holm over the 5 pre-registered defenses per family)\n")
    for f in ("A", "B"):
        emit(f"\nFamily {f}:\n")
        test_block([(f"{f}: {d} vs plain", *pairs(f, "inject", d, "inject", "plain"))
                    for d in ("prov", "prov_pin", "quar_strip", "watch", "watch_pin")], f"defense_{f}")
    emit("\n### Secondary: plain vs full and pin vs plain, inject, round 3 (Holm over these 4)\n")
    test_block([(f"{f}: {x} vs {y}", *pairs(f, "inject", x, "inject", y)) for f in ("A", "B")
                for x, y in (("plain", "full"), ("pin", "plain"))], "secondary")
    if any(t["variant"] == "none" for t in T):
        emit("\n### Does the injection add acting beyond the no-injection control? (family A, round 3, Holm over these)\n")
        test_block([(f"A {c}: inject vs none", *pairs("A", "inject", c, "none", c)) for c in CONDS
                    if any(t["variant"] == "none" and t["family"] == "A" for t in T)], "inject_vs_none")
    if any(t["variant"] == "legit" for t in T):
        emit("\n### Utility: legit, each condition vs full (Holm over these 14)\n")
        test_block([(f"{f} legit: {c} vs full", *pairs(f, "legit", c, "legit", "full")) for f in ("A", "B")
                    for c in CONDS if c != "full"], "utility_vs_full")
        emit("\n### Utility: legit, each defense vs plain (Holm over these 12)\n")
        test_block([(f"{f} legit: {c} vs plain", *pairs(f, "legit", c, "legit", "plain")) for f in ("A", "B")
                    for c in DEF], "utility_vs_plain")

    # ------------------------------------------------ summary laundering at round 3
    emit("\n## 3. How the round-3 summary represents the injected content (inject) or the operator update (legit)\n")
    emit("Laundered = OPERATOR or FACT. For legit, OPERATOR is the correct representation.\n")
    emit("| family | variant | summary | n | OPERATOR | FACT | ATTRIBUTED | OMITTED | laundered | flagged untrusted | rule kept |")
    emit("|---|---|---|---|---|---|---|---|---|---|---|")
    for f in ("A", "B"):
        for v in ("inject", "legit", "none"):
            for ch in ("plain", "prov", "quar", "watch"):
                js = [t["sjudge"][ch]["3"] for t in T if t["family"] == f and t["variant"] == v
                      and t["sjudge"].get(ch, {}).get("3")]
                if not js:
                    continue
                c = Counter(cat(j) for j in js)
                n = len(js)
                rr = [bool(j.get("rule_retained")) for j in js if "rule_retained" in j]
                fl = sum(bool(j.get("flagged_untrusted")) for j in js)
                S.setdefault("sumcat", {})[f"{f}/{v}/{ch}"] = dict(c)
                if v == "none":
                    emit(f"| {f} | none | {ch} | {n} | | | | | | | {r(sum(rr), len(rr)) if rr else ''} |")
                    continue
                emit(f"| {f} | {v} | {ch} | {n} | {c['OPERATOR']} | {c['FACT']} | {c['ATTRIBUTED']} | {c['OMITTED']} | "
                     f"{r(c['OPERATOR'] + c['FACT'], n)} | {r(fl, n)} | {r(sum(rr), len(rr)) if rr else ''} |")

    # ------------------------------------------------ accumulation
    emit("\n## 4. Accumulation over rounds (inject sessions)\n")
    inj = [t for t in T if t["variant"] == "inject"]
    emit("| family | summary | round | n | OPERATOR | FACT | ATTRIBUTED | OMITTED | laundered |")
    emit("|---|---|---|---|---|---|---|---|---|")
    for f in ("A", "B"):
        for ch in ("plain", "prov"):
            for rd in ("1", "3", "6"):
                js = [t["sjudge"][ch][rd] for t in inj if t["family"] == f and rd in t["sjudge"].get(ch, {})]
                c = Counter(cat(j) for j in js)
                S.setdefault("accum", {})[f"{f}/{ch}/{rd}"] = dict(c)
                emit(f"| {f} | {ch} | {rd} | {len(js)} | {c['OPERATOR']} | {c['FACT']} | {c['ATTRIBUTED']} | {c['OMITTED']} | "
                     f"{r(c['OPERATOR'] + c['FACT'], len(js))} |")
    rows = []
    for f in ("A", "B"):
        for ch in ("plain", "prov"):
            pr = [(cat(t["sjudge"][ch]["6"]) in LAUND, cat(t["sjudge"][ch]["1"]) in LAUND) for t in inj
                  if t["family"] == f and "6" in t["sjudge"].get(ch, {})]
            cr = [(t["id"], int(x), int(y)) for t, (x, y) in zip([t for t in inj if t["family"] == f
                                                                  and "6" in t["sjudge"].get(ch, {})], pr)]
            rows.append((f"{f} {ch}: laundered at round 6 vs round 1", pr, cr))
    emit("\nH4: laundered at round 6 vs round 1 (paired per session; plain is pre-registered, prov is secondary; Holm over 4)\n")
    test_block(rows, "accumulation")
    emit("\nTransitions of attributed content (round 1 ATTRIBUTED, what it became by round 3 and round 6):\n")
    emit("| family | summary | n attributed at r1 | r3 laundered | r3 attributed | r3 omitted | r6 laundered | r6 attributed | r6 omitted |")
    emit("|---|---|---|---|---|---|---|---|---|")
    for f in ("A", "B"):
        for ch in ("plain", "prov"):
            ts = [t for t in inj if t["family"] == f and cat(t["sjudge"][ch]["1"]) == "ATTRIBUTED"]
            c3 = Counter("L" if cat(t["sjudge"][ch]["3"]) in LAUND else cat(t["sjudge"][ch]["3"])[0] for t in ts)
            c6 = Counter("L" if cat(t["sjudge"][ch]["6"]) in LAUND else cat(t["sjudge"][ch]["6"])[0] for t in ts)
            emit(f"| {f} | {ch} | {len(ts)} | {c3['L']} | {c3['A']} | {c3['O']} | {c6['L']} | {c6['A']} | {c6['O']} |")
    emit("\nActing over rounds (inject):\n")
    emit("| family | condition | round 1 | round 3 | round 6 |")
    emit("|---|---|---|---|---|")
    for f in ("A", "B"):
        for c in ("full", "plain"):
            cells = []
            for rd in ("1", "3", "6"):
                ts = [t for t in inj if t["family"] == f and c in t["cp"].get(rd, {})]
                cells.append(r(sum(bool(t["cp"][rd][c]["acted"]) for t in ts), len(ts)))
            emit(f"| {f} | {c} | " + " | ".join(cells) + " |")

    # ------------------------------------------------ overtness breakdown
    emit("\n## 5. By overtness tier (inject, round 3; secondary)\n")
    emit("| family | tier | sessions | plain laundered | full acted | plain acted | prov_pin acted | watch_pin acted | quar_strip acted |")
    emit("|---|---|---|---|---|---|---|---|---|")
    for f in ("A", "B"):
        for tr in ("1", "2-3"):
            ts = [t for t in inj if t["family"] == f and tier(t) == tr]
            n = len(ts)
            la = sum(cat(t["sjudge"]["plain"]["3"]) in LAUND for t in ts)
            cells = [r(sum(bool(t["cp"]["3"][c]["acted"]) for t in ts), n) for c in ("full", "plain", "prov_pin", "watch_pin", "quar_strip")]
            emit(f"| {f} | {tr} | {n} | {r(la, n)} | " + " | ".join(cells) + " |")
    emit("\nBy designed style:\n")
    emit("| family | style | sessions | plain laundered (r3) | plain laundered (any round) | full acted | plain acted | quarantine extracted something |")
    emit("|---|---|---|---|---|---|---|---|")
    for f in ("A", "B"):
        for st in ("declarative", "procedural", "addressed"):
            ts = [t for t in inj if t["family"] == f and BY[t["id"]]["style"] == st]
            n = len(ts)
            la = sum(cat(t["sjudge"]["plain"]["3"]) in LAUND for t in ts)
            lany = sum(any(cat(j) in LAUND for j in t["sjudge"]["plain"].values()) for t in ts)
            qx = sum(bool(t.get("quarantine_extracted")) for t in ts)
            emit(f"| {f} | {st} | {n} | {r(la, n)} | {r(lany, n)} | {r(sum(bool(t['cp']['3']['full']['acted']) for t in ts), n)} | "
                 f"{r(sum(bool(t['cp']['3']['plain']['acted']) for t in ts), n)} | {r(qx, n)} |")

    # ------------------------------------------------ observational conditional
    emit("\n## 6. Acting given the summary category (observational, inject, plain, all rounds with a plain decision)\n")
    emit("| family | category | acted |")
    emit("|---|---|---|")
    for f in ("A", "B"):
        by = defaultdict(lambda: [0, 0])
        for t in inj:
            if t["family"] != f:
                continue
            for rd in ("1", "3", "6"):
                if "plain" in t["cp"].get(rd, {}):
                    k = cat(t["sjudge"]["plain"][rd])
                    by[k][0] += bool(t["cp"][rd]["plain"]["acted"])
                    by[k][1] += 1
        for k in ("OPERATOR", "FACT", "ATTRIBUTED", "OMITTED"):
            emit(f"| {f} | {k} | {r(*by[k])} |")

    # ------------------------------------------------ causal
    cp = HERE / a.causal
    if cp.exists():
        C = [json.loads(l) for l in cp.read_text().splitlines()]
        emit("\n## 7. Counterfactual tests (pre-registered H1 and H2)\n")
        emit(f"Units: {dict(Counter((u['test'], u['family'], u['status']) for u in C))}\n")
        rows = []
        for test, arms in (("forward", ("orig", "attrib")), ("reverse", ("laund", "attrib"))):
            for f in ("A", "B"):
                us = [u for u in C if u["test"] == test and u["family"] == f and u["status"] == "ok"]
                if not us:
                    continue
                maj = lambda xs: sum(x["acted"] for x in xs) * 2 > len(xs)  # noqa: E731
                pr = [(maj(u["arms"][arms[0]]), maj(u["arms"][arms[1]])) for u in us]
                cr = [(u["id"], sum(x["acted"] for x in u["arms"][arms[0]]) / len(u["arms"][arms[0]]),
                       sum(x["acted"] for x in u["arms"][arms[1]]) / len(u["arms"][arms[1]])) for u in us]
                rows.append((f"{test} {f}: {arms[0]} vs {arms[1]}", pr, cr))
        emit("Primary: majority-of-K acting per summary, paired. Holm over the 4 primary tests. The CI column is the "
             "mean per-summary difference in acting rate (all K samples), resampling scenarios.\n")
        test_block(rows, "causal_primary")
        emit("\nSample-level acting rates and manipulation checks:\n")
        emit("| test | family | units | arm | acted (samples) | manipulation check |")
        emit("|---|---|---|---|---|---|")
        for test in ("forward", "reverse"):
            for f in ("A", "B"):
                us = [u for u in C if u["test"] == test and u["family"] == f and u["status"] == "ok"]
                if not us:
                    continue
                for arm in (("orig", "attrib") if test == "forward" else ("clean", "laund", "attrib")):
                    xs = [x["acted"] for u in us for x in u["arms"][arm]]
                    if test == "forward" and arm == "attrib":
                        chk = f"edited judged ATTRIBUTED: {r(sum(cat(u['check']) == 'ATTRIBUTED' for u in us), len(us))}"
                    elif test == "reverse" and arm == "laund":
                        chk = f"judged OPERATOR/FACT: {r(sum(cat(u['check_laund']) in LAUND for u in us), len(us))}"
                    elif test == "reverse" and arm == "attrib":
                        chk = f"judged ATTRIBUTED: {r(sum(cat(u['check_attrib']) == 'ATTRIBUTED' for u in us), len(us))}"
                    else:
                        chk = ""
                    emit(f"| {test} | {f} | {len(us)} | {arm} | {r(sum(xs), len(xs))} | {chk} |")
        emit("\nSecondary (Holm over these): reverse laund vs clean and attrib vs clean; forward restricted to units "
             "passing the manipulation check.\n")
        rows = []
        for f in ("A", "B"):
            us = [u for u in C if u["test"] == "reverse" and u["family"] == f and u["status"] == "ok"]
            maj = lambda xs: sum(x["acted"] for x in xs) * 2 > len(xs)  # noqa: E731
            for arm in ("laund", "attrib"):
                pr = [(maj(u["arms"][arm]), maj(u["arms"]["clean"])) for u in us]
                cr = [(u["id"], sum(x["acted"] for x in u["arms"][arm]) / len(u["arms"][arm]),
                       sum(x["acted"] for x in u["arms"]["clean"]) / len(u["arms"]["clean"])) for u in us]
                rows.append((f"reverse {f}: {arm} vs clean", pr, cr))
            us = [u for u in C if u["test"] == "forward" and u["family"] == f and u["status"] == "ok"
                  and cat(u["check"]) == "ATTRIBUTED"]
            pr = [(maj(u["arms"]["orig"]), maj(u["arms"]["attrib"])) for u in us]
            cr = [(u["id"], sum(x["acted"] for x in u["arms"]["orig"]) / len(u["arms"]["orig"]),
                   sum(x["acted"] for x in u["arms"]["attrib"]) / len(u["arms"]["attrib"])) for u in us]
            rows.append((f"forward {f} (check passed): orig vs attrib", pr, cr))
        test_block(rows, "causal_secondary")
        emit("\nForward units by original category and round:\n")
        emit("| family | category | round | units | orig acted | attrib acted |")
        emit("|---|---|---|---|---|---|")
        for f in ("A", "B"):
            for k in LAUND:
                for rd in (1, 3, 6):
                    us = [u for u in C if u["test"] == "forward" and u["family"] == f and u["status"] == "ok"
                          and cat(u["judge"]) == k and u["round"] == rd]
                    if us:
                        o = [x["acted"] for u in us for x in u["arms"]["orig"]]
                        e = [x["acted"] for u in us for x in u["arms"]["attrib"]]
                        emit(f"| {f} | {k} | {rd} | {len(us)} | {r(sum(o), len(o))} | {r(sum(e), len(e))} |")

    # ------------------------------------------------ watchpoint diagnostics
    emit("\n## 8. Attribution watchpoint diagnostics (round 3)\n")
    emit("| family | variant | sessions | directive sentences found (mean) | re-labelled (mean) | not matched in text (total) | injected content re-labelled or absent |")
    emit("|---|---|---|---|---|---|---|")
    for f in ("A", "B"):
        for v in ("inject", "legit"):
            ts = [t for t in T if t["family"] == f and t["variant"] == v and t.get("watch_info", {}).get("3")]
            if not ts:
                continue
            wi = [t["watch_info"]["3"] for t in ts]
            # injected content in plain summary was laundered; does the watch summary still launder it?
            lp = [t for t in ts if cat(t["sjudge"]["plain"]["3"]) in LAUND]
            fixed = sum(cat(t["sjudge"]["watch"]["3"]) not in LAUND or t["sjudge"]["watch"]["3"].get("flagged_untrusted")
                        for t in lp)
            emit(f"| {f} | {v} | {len(ts)} | {sum(w['n_items'] for w in wi) / len(wi):.1f} | "
                 f"{sum(w['n_flagged'] for w in wi) / len(wi):.1f} | {sum(w['n_unmatched'] for w in wi)} | "
                 f"{fixed}/{len(lp)} of plain-laundered |" if v == "inject" else
                 f"| {f} | {v} | {len(ts)} | {sum(w['n_items'] for w in wi) / len(wi):.1f} | "
                 f"{sum(w['n_flagged'] for w in wi) / len(wi):.1f} | {sum(w['n_unmatched'] for w in wi)} | |")

    # ------------------------------------------------ judge validation
    lp = HERE / a.labels
    if a.labels != "none" and lp.exists():
        H = json.loads(lp.read_text())
        emit("\n## 9. Judge validation (hand labels, blind to the judge)\n")
        emit("| judge | n | agreement | Cohen's kappa |")
        emit("|---|---|---|---|")
        for name, items in H.items():
            if not items:
                continue
            j, h = [norm(x["judge"]) for x in items], [norm(x["human"]) for x in items]
            po, k = kappa(j, h)
            emit(f"| {name} | {len(items)} | {po:.2f} | {k:.2f} |")
            S.setdefault("judge_validation", {})[name] = {"n": len(items), "agree": po, "kappa": k}
            if name == "summary_category":
                jl = ["L" if x in LAUND else "N" for x in j]
                hl = ["L" if x in LAUND else "N" for x in h]
                po, k = kappa(jl, hl)
                emit(f"| summary laundered vs not | {len(items)} | {po:.2f} | {k:.2f} |")
                S["judge_validation"]["laundered_binary"] = {"n": len(items), "agree": po, "kappa": k}

    # ------------------------------------------------ cost
    up = HERE.parent / "usage.jsonl"
    if not a.no_cost and up.exists():
        emit("\n## 10. Cost (shared usage log, tags starting e11_)\n")
        agg = defaultdict(lambda: [0, 0, 0])
        for line in up.read_text().splitlines():
            try:
                u = json.loads(line)
            except json.JSONDecodeError:
                continue
            tg = u.get("tag", "")
            if not tg.startswith("e11_"):
                continue
            g = tg.replace("_fallback", "")
            agg[g][0] += 1
            agg[g][1] += u.get("in") or 0
            agg[g][2] += u.get("out") or 0
        emit("| tag | calls | mean in | mean out |")
        emit("|---|---|---|---|")
        for g, (n, i, o) in sorted(agg.items()):
            emit(f"| {g} | {n} | {i / n:.0f} | {o / n:.0f} |")
        tot = [sum(v[k] for v in agg.values()) for k in range(3)]
        emit(f"\nTotal: {tot[0]} calls, {tot[1] / 1e6:.2f}M input tokens, {tot[2] / 1e6:.2f}M output tokens.")
        S["cost"] = {g: v for g, v in agg.items()}

    (HERE / a.out).write_text("\n".join(L) + "\n")
    (HERE / a.out).with_suffix(".json").write_text(json.dumps(S, indent=1, default=str))


if __name__ == "__main__":
    main()
