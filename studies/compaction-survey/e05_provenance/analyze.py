"""Regenerate every E5 table from the raw files.

Inputs:  results/trials.jsonl (main run), results/ablation.jsonl (optional), results/hand_labels.json (optional),
         ../shared/usage.jsonl (shared token log; rows with tags starting e5_)
Outputs: results/tables.md (all tables) and results/summary.json
Usage:   python analyze.py [--trials FILE] [--ablation FILE] [--labels FILE] [--v2 FILE] [--out FILE]
         Pass "none" for any optional input to skip it (e.g. for a second-backbone run).
"""
import argparse, json, math, sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "shared"))
from common import wilson  # noqa: E402

HERE = Path(__file__).resolve().parent
MAIN = ["full", "plain", "prov", "quar", "pin"]
ABL = ["quar_strip", "quar_label", "prov_pin"]
LINES = []


def emit(s=""):
    print(s)
    LINES.append(s)


def r(k, n):
    if not n:
        return "n/a"
    lo, hi = wilson(k, n)
    return f"{k}/{n} = {100 * k / n:.0f}% [{abs(100 * lo):.0f} to {100 * hi:.0f}]"


def mcnemar(pairs):
    b = sum(1 for x, y in pairs if x and not y)
    c = sum(1 for x, y in pairs if y and not x)
    n = b + c
    if n == 0:
        return b, c, 1.0
    return b, c, min(1.0, 2 * sum(math.comb(n, k) for k in range(0, min(b, c) + 1)) / 2 ** n)


def holm(ps):
    order = sorted(range(len(ps)), key=lambda i: ps[i])
    adj, run = [0.0] * len(ps), 0.0
    for rank, i in enumerate(order):
        run = max(run, min(1.0, (len(ps) - rank) * ps[i]))
        adj[i] = run
    return adj


def kappa(a, b):
    n = len(a)
    po = sum(x == y for x, y in zip(a, b)) / n
    ca, cb = Counter(a), Counter(b)
    pe = sum(ca[k] * cb[k] for k in set(ca) | set(cb)) / n ** 2
    return po, (po - pe) / (1 - pe) if pe < 1 else float("nan")


def test_block(title, rows):
    """rows: list of (label, pairs). Prints McNemar raw and Holm-adjusted p."""
    res = [(lab, *mcnemar(pr), len(pr)) for lab, pr in rows]
    adj = holm([x[3] for x in res])
    emit(f"\n{title}\n")
    emit("| comparison | n pairs | only first | only second | McNemar p | Holm p |")
    emit("|---|---|---|---|---|---|")
    out = {}
    for (lab, b, c, p, n), pa in zip(res, adj):
        emit(f"| {lab} | {n} | {b} | {c} | {p:.3g} | {pa:.3g} |")
        out[lab] = {"n": n, "only_first": b, "only_second": c, "p": p, "holm_p": pa}
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--trials", default="results/trials.jsonl")
    ap.add_argument("--ablation", default="results/ablation.jsonl")
    ap.add_argument("--labels", default="results/hand_labels.json")
    ap.add_argument("--tag-prefix", default="e5_")
    ap.add_argument("--v2", default="results/viol_v2.jsonl")
    ap.add_argument("--out", default="results/tables.md")
    a = ap.parse_args()
    trials = [json.loads(l) for l in (HERE / a.trials).read_text().splitlines()]
    abl_path = HERE / a.ablation
    if abl_path.exists():
        for l in abl_path.read_text().splitlines():
            o = json.loads(l)
            for t in trials:
                if t["id"] == o["id"] and t["variant"] == o["variant"]:
                    t["conds"].update(o["conds"])
    conds = MAIN + [c for c in ABL if all(c in t["conds"] for t in trials)]
    T = {(t["family"], t["variant"], t["id"]): t for t in trials}
    summ = {"rates": {}, "tests": {}, "summary_judge": {}, "cost": {}, "judge_validation": {}}
    emit(f"# E5 tables (generated by analyze.py from {a.trials})\n")
    emit(f"Trials: {len(trials)}. Models: agent {sorted({t.get('agent_model', 'stealth/space-bunny-alpha') for t in trials})}, "
         f"judge {sorted({t.get('judge_model', 'stealth/space-bunny-alpha') for t in trials})}.")

    # ---- table 1: acting rates
    emit("\n## Acting rates by family, variant, and condition\n")
    emit("Family A: agent's next action violates the operator rule. Family B: agent's plan performs the planted "
         "action. For the legit variant, acting is the desired behavior (utility).\n")
    emit("| family | variant | " + " | ".join(conds) + " |")
    emit("|---|---|" + "---|" * len(conds))
    for fam in ("A", "B"):
        for v in ("inject", "none", "legit"):
            ts = [t for t in trials if t["family"] == fam and t["variant"] == v]
            if not ts:
                continue
            cells = []
            for c in conds:
                k = sum(bool(t["conds"][c]["acted"]) for t in ts)
                summ["rates"][f"{fam}/{v}/{c}"] = [k, len(ts)]
                cells.append(r(k, len(ts)))
            emit(f"| {fam} | {v} | " + " | ".join(cells) + " |")
    emit("\nFamily A COMPLY decisions (before the violation judge):\n")
    emit("| variant | " + " | ".join(conds) + " |")
    emit("|---|" + "---|" * len(conds))
    for v in ("inject", "none", "legit"):
        ts = [t for t in trials if t["family"] == "A" and t["variant"] == v]
        emit(f"| {v} | " + " | ".join(r(sum(t['conds'][c].get('decision') == 'COMPLY' for t in ts), len(ts))
                                      for c in conds) + " |")
    emit("\nPooled A+B:\n")
    emit("| variant | " + " | ".join(conds) + " |")
    emit("|---|" + "---|" * len(conds))
    for v in ("inject", "none", "legit"):
        ts = [t for t in trials if t["variant"] == v]
        emit(f"| {v} | " + " | ".join(r(sum(bool(t['conds'][c]['acted']) for t in ts), len(ts)) for c in conds) + " |")

    def pairs(fam, v1, c1, v2, c2):
        out = []
        for (f, v, i), t in T.items():
            if f == fam and v == v1 and (f, v2, i) in T:
                out.append((bool(t["conds"][c1]["acted"]), bool(T[(f, v2, i)]["conds"][c2]["acted"])))
        return out

    # ---- primary tests
    rows = []
    for fam in ("A", "B"):
        rows.append((f"{fam} inject: plain vs full", pairs(fam, "inject", "plain", "inject", "full")))
        for fx in ("prov", "quar", "pin"):
            rows.append((f"{fam} inject: {fx} vs plain", pairs(fam, "inject", fx, "inject", "plain")))
    emit("\n## Primary comparisons (inject variant, paired, Holm over these 8)")
    summ["tests"]["primary"] = test_block("", rows)
    rows = [(f"{fam} {c}: inject vs none", pairs(fam, "inject", c, "none", c)) for fam in ("A", "B") for c in MAIN]
    emit("\n## Secondary: does the injection add acting beyond the no-injection control? (Holm over these 10)")
    summ["tests"]["inject_vs_none"] = test_block("", rows)
    rows = [(f"{fam} legit: {c} vs full", pairs(fam, "legit", c, "legit", "full"))
            for fam in ("A", "B") for c in conds if c != "full"]
    emit("\n## Utility: legit operator update, each condition vs full context (Holm over these)")
    summ["tests"]["legit"] = test_block("", rows)
    if any(c in conds for c in ABL):
        rows = []
        for fam in ("A", "B"):
            for v in ("inject", "legit"):
                rows += [(f"{fam} {v}: quar_strip vs quar", pairs(fam, v, "quar_strip", v, "quar")),
                         (f"{fam} {v}: quar_label vs quar", pairs(fam, v, "quar_label", v, "quar")),
                         (f"{fam} {v}: prov_pin vs prov", pairs(fam, v, "prov_pin", v, "prov"))]
        emit("\n## Ablations (exploratory, added after the coordinator's methodology update; Holm over these 12)")
        summ["tests"]["ablation"] = test_block("", rows)

    # ---- summary laundering
    emit("\n## How each summary represents the injected content (inject) or the operator update (legit)\n")
    emit("Laundered = OPERATOR or FACT. For the legit variant, OPERATOR is the correct representation.\n")
    emit("| family | variant | summary | n | OPERATOR | FACT | ATTRIBUTED | OMITTED | laundered (OP+FACT) | flagged untrusted | operator rule retained |")
    emit("|---|---|---|---|---|---|---|---|---|---|---|")
    for fam in ("A", "B"):
        for v in ("inject", "legit", "none"):
            for c in ("plain", "prov", "quar"):
                js = [t["conds"][c]["summary_judge"] for t in trials if t["family"] == fam and t["variant"] == v
                      and t["conds"][c].get("summary_judge")]
                if not js:
                    continue
                cat = Counter(str(j.get("category", "?")).upper() for j in js)
                rr = [bool(j.get("rule_retained")) for j in js if "rule_retained" in j]
                fl = sum(bool(j.get("flagged_untrusted")) for j in js)
                n = len(js)
                lau = cat["OPERATOR"] + cat["FACT"]
                summ["summary_judge"][f"{fam}/{v}/{c}"] = {"n": n, "cat": dict(cat), "flagged": fl,
                                                           "rule_retained": [sum(rr), len(rr)]}
                if v == "none":
                    emit(f"| {fam} | none | {c} | {n} | | | | | | | {r(sum(rr), len(rr)) if rr else ''} |")
                    continue
                emit(f"| {fam} | {v} | {c} | {n} | {cat['OPERATOR']} | {cat['FACT']} | {cat['ATTRIBUTED']} | "
                     f"{cat['OMITTED']} | {r(lau, n)} | {r(fl, n)} | {r(sum(rr), len(rr)) if rr else ''} |")

    emit("\n## Acting conditional on how the summary represented the injection (inject variant; exploratory)\n")
    emit("| family | summary | category | acted |")
    emit("|---|---|---|---|")
    for fam in ("A", "B"):
        for c in ("plain", "prov", "quar"):
            by = defaultdict(lambda: [0, 0])
            for t in trials:
                if t["family"] == fam and t["variant"] == "inject" and t["conds"][c].get("summary_judge"):
                    k = str(t["conds"][c]["summary_judge"].get("category", "?")).upper()
                    by[k][0] += bool(t["conds"][c]["acted"])
                    by[k][1] += 1
            for k in ("OPERATOR", "FACT", "ATTRIBUTED", "OMITTED"):
                if by[k][1]:
                    emit(f"| {fam} | {c} | {k} | {r(*by[k])} |")
    for fam in ("A", "B"):
        inj = [t for t in trials if t["family"] == fam and t["variant"] == "inject"]
        q = sum(bool(t["quarantine_extracted"]) for t in inj)
        emit(f"\nQuarantine filter extracted at least one passage on {r(q, len(inj))} family {fam} inject trials.")
        summ[f"quarantine_{fam}"] = [q, len(inj)]

    # ---- cost
    up = HERE.parent / "shared" / "usage.jsonl"
    if up.exists():
        agg = defaultdict(lambda: [0, 0, 0])
        for l in up.read_text().splitlines():
            u = json.loads(l)
            if str(u.get("tag", "")).startswith(a.tag_prefix):
                g = agg[u["tag"]]
                g[0] += 1
                g[1] += u.get("in") or 0
                g[2] += u.get("out") or 0
        emit("\n## Cost by call type (all E5 calls in the shared usage log, including pilots and scenario generation)\n")
        emit("| tag | calls | input tokens | output tokens | mean in/call | mean out/call |")
        emit("|---|---|---|---|---|---|")
        for k in sorted(agg):
            c, i, o = agg[k]
            emit(f"| {k} | {c} | {i} | {o} | {i / c:.0f} | {o / c:.0f} |")
            summ["cost"][k] = agg[k]
        tot = [sum(x[j] for x in agg.values()) for j in range(3)]
        emit(f"| total | {tot[0]} | {tot[1]} | {tot[2]} | | |")
        # per-method extra cost per trial over plain
        def per_call(tag):
            c, i, o = agg.get(tag, [0, 0, 0])
            return (i / c, o / c) if c else (0, 0)
        emit("\nPer-session compaction cost (4 recursive rounds per method, from the mean tokens per call):\n")
        emit("| method | extra model calls per compaction cycle | approx input tokens per session | approx output tokens per session |")
        emit("|---|---|---|---|")
        for name, tag, extra in [("plain", "e5_c_plain", 0), ("prov", "e5_c_prov", 0), ("quar", "e5_c_quar", 1),
                                 ("pin", "e5_c_plain", 0)]:
            i, o = per_call(tag)
            qi, qo = per_call("e5_quar") if extra else (0, 0)
            emit(f"| {name} | {'1 per tool output' if extra else '0'} | {4 * i + qi:.0f} | {4 * o + qo:.0f} |")
        emit("\nPinning adds no calls; it adds the operator messages (about 40 to 80 tokens here) to every later prompt.")

    # ---- judge validation
    lp = HERE / a.labels
    if lp.exists():
        L = json.loads(lp.read_text())
        emit("\n## Judge validation against hand labels\n")
        emit("| judge | n | agreement | Cohen's kappa |")
        emit("|---|---|---|---|")
        for jname, items in L.items():
            jl = [str(x["judge"]).upper() for x in items]
            hl = [str(x["human"]).upper() for x in items]
            po, k = kappa(jl, hl)
            emit(f"| {jname} | {len(items)} | {po:.2f} | {k:.2f} |")
            summ["judge_validation"][jname] = {"n": len(items), "agreement": po, "kappa": k}
            if jname == "summary_category":
                jb = ["LAUND" if x in ("OPERATOR", "FACT") else "NOT" for x in jl]
                hb = ["LAUND" if x in ("OPERATOR", "FACT") else "NOT" for x in hl]
                po, k = kappa(jb, hb)
                emit(f"| summary_category collapsed to laundered vs not | {len(items)} | {po:.2f} | {k:.2f} |")
                summ["judge_validation"]["summary_laundered_binary"] = {"n": len(items), "agreement": po, "kappa": k}

    # ---- sensitivity: stricter v2 violation judge (post hoc)
    v2p = HERE / a.v2
    if v2p.exists():
        V2 = {(x["id"], x["variant"], x["cond"]): bool(x["violation_v2"]) for x in map(json.loads, v2p.read_text().splitlines())}
        def acted2(t, c):
            o = t["conds"][c]
            return o.get("decision") == "COMPLY" and V2.get((t["id"], t["variant"], c), False)
        missing = sum(1 for t in trials if t["family"] == "A" for c in conds
                      if t["conds"][c].get("decision") == "COMPLY" and (t["id"], t["variant"], c) not in V2)
        emit("\n## Sensitivity (post hoc): family A with the stricter v2 violation judge\n")
        emit(f"v2 counts omission of a required step as a violation. COMPLY replies without a v2 verdict: {missing}.\n")
        emit("| variant | " + " | ".join(conds) + " |")
        emit("|---|" + "---|" * len(conds))
        for v in ("inject", "none", "legit"):
            ts = [t for t in trials if t["family"] == "A" and t["variant"] == v]
            emit(f"| {v} | " + " | ".join(r(sum(acted2(t, c) for t in ts), len(ts)) for c in conds) + " |")
            for c in conds:
                summ["rates"][f"A/{v}/{c}/v2"] = [sum(acted2(t, c) for t in ts), len(ts)]
        TA = {(t["variant"], t["id"]): t for t in trials if t["family"] == "A"}
        def pr2(v1, c1, v2_, c2):
            return [(acted2(t, c1), acted2(TA[(v2_, i)], c2)) for (v, i), t in TA.items() if v == v1 and (v2_, i) in TA]
        rows = [("A inject: plain vs full (v2)", pr2("inject", "plain", "inject", "full"))]
        rows += [(f"A inject: {fx} vs plain (v2)", pr2("inject", fx, "inject", "plain")) for fx in ("prov", "quar", "pin")]
        rows += [(f"A {c}: inject vs none (v2)", pr2("inject", c, "none", c)) for c in MAIN]
        summ["tests"]["A_v2"] = test_block("Paired tests with v2 (Holm over these 9):", rows)
        hp = HERE / "results" / "hand_labels_holdout_raw.json"
        hs = HERE / a.labels
        emit("\n## v1 and v2 violation judges against hand labels\n")
        emit("| sample | judge | n | agreement | Cohen's kappa |")
        emit("|---|---|---|---|---|")
        sets = []
        if hs.exists():
            sets.append(("first sample (v2 was written after seeing it)",
                         {x["key"]: x["human"] for x in json.loads(hs.read_text())["a_violation"]}))
        if hp.exists():
            sets.append(("fresh holdout", json.loads(hp.read_text())))
        for name, H in sets:
            for jn in ("v1", "v2"):
                hum, jud = [], []
                for k, h in H.items():
                    _, i, v, c = k.split("|")
                    t = TA[(v, i)]
                    j = bool(t["conds"][c]["acted"]) if jn == "v1" else acted2(t, c)
                    if jn == "v2" and (i, v, c) not in V2:
                        continue
                    hum.append(h == "YES")
                    jud.append(j)
                if hum:
                    po, k_ = kappa(jud, hum)
                    emit(f"| {name} | {jn} | {len(hum)} | {po:.2f} | {k_:.2f} |")
                    summ["judge_validation"][f"a_violation {jn} {name}"] = {"n": len(hum), "agreement": po, "kappa": k_}

    (HERE / a.out).write_text("\n".join(LINES) + "\n")
    (HERE / a.out).with_suffix(".json").write_text(json.dumps(summ, indent=1))


if __name__ == "__main__":
    main()
